# search_meme_wiki 工具说明：这是模型能看到的唯一说明，保留「不确定就查、查到先接梗、别传整句」三条
TOOL_DESCRIPTION = (
    "查询网络梗、流行语、缩写、黑话或群内自造词的含义与出处（内置 6000+ 条词库，毫秒级）。"
    "只要消息里出现你没有十足把握的网络新词、梗、缩写或黑话（比如「大水理论」「寿来」「飞八分钱」），"
    "就先调用本工具查一下再决定怎么回；不确定就直接查，不要先猜、不要反问用户「这是啥」。"
    "对方问「这是什么梗」「这词啥意思」「XX是谁说的」时同样调用。"
    "查到结果后优先用它接梗（照着「怎么用」里的说法回一句），不要当词典条目念；"
    "只有对方明确问含义或实在接不上时才解释出处。"
    "只传那个词或短语（建议不超过 8 个字），不要传整句话。"
    "百分之百确定的常见词（如「典」「草」「6」）不用查。查不到就如实说不知道，不要编造。"
)

NOT_FOUND_PREFIX = "词库里没有收录"


def not_found_text(query: str) -> str:
    return f"{NOT_FOUND_PREFIX}「{query}」。这可能是刚出现的新梗、群内自造词，或者拼写不对。"


def dict_hint(query: str, text: str) -> str:
    return (
        "[梗词库内部资料·仅用于理解，禁止原样输出]\n"
        f"这是「{query}」的资料。**优先用这个词接梗**：照着【怎么用 / 怎么接】里的说法、"
        "动作或句式，用你自己的口气回一句；对方没明确问含义时，**不要主动解释典故**。"
        "只有在对方明确问「这是什么梗/啥意思」，或者实在接不上时，才用一两句解释出处。"
        "不要复述标题、标签、来源，不要整段照抄，也不要说\"我查了一下\"。\n\n" + text
    )


def miss_hint(query: str) -> str:
    """词库没收录时：提示模型用 MaiBot 自带的 web_search 工具自己查。"""
    return (
        f"[梗百科] 词库里没有收录「{query}」。\n"
        "如果这个词看起来像网络梗/缩写/黑话，而你也不确定它的意思：\n"
        "1. 如果你能用 `web_search` 工具，先搜一下再决定怎么回；\n"
        "2. 搜不到、或者搜索结果里没有明确说法，就老实说不知道，或者反问一句「这什么梗」；\n"
        "3. **绝对不要硬解释、也不要把两个不相干的梗拼在一起**——装懂比不知道更糟。"
    )


def no_search_hint(query: str) -> str:
    """不联网（search_mode=off）时的轻提示：别硬解释就行。"""
    return (
        f"[梗百科] 词库里没有「{query}」，这次没有联网查。\n"
        "如果不确定它是什么意思：别硬解释、别编，最多反问一句「这什么梗」，或者顺着上下文别接这个点。"
    )
